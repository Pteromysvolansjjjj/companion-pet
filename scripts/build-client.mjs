import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = readFileSync(join(root, 'src/client/chat-filter.mjs'), 'utf8');
if (/^import\s/m.test(source)) throw new Error('Client source must stay self-contained');
const body = source.replace(/^export (?=function |const )/gm, '');
writeFileSync(join(root, 'client.js'), `// Generated by scripts/build-client.mjs; do not edit directly.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-plugin-lol-companion',\n  factory: () => {\n${body}\n    return { inject: ['uiConversation', 'uiSession'], apply: mountChatFilter };\n  },\n});\n`);
